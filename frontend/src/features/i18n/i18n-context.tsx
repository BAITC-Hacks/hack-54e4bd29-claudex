type I18nValue = { language: Language; setLanguage: (language: Language) => void; t: (text: string) => string };
const defaultI18n: I18nValue = { language: "ru", setLanguage: () => undefined, t: (text) => text };
const I18nContext = createContext<I18nValue>(defaultI18n);
const ru = Object.fromEntries(Object.entries(kk).map(([source, translated]) => [translated, source]));
type OriginalValue = { source: string; rendered: string };
const originalText = new WeakMap<Text, OriginalValue>();
const originalAttributes = new WeakMap<Element, Map<string, OriginalValue>>();

function translate(text: string, language: Language): string {
  if (!text.trim()) return text;
  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  const core = text.slice(leading.length, text.length - trailing.length);
  const visibleCore = core;
  const normalizedCore = language === "ru"
    ? visibleCore
      .replaceAll("Медициналық ұйым", "Медицинская организация")
      .replaceAll("Болжам ауқымы:", "Область прогноза:")
      .replaceAll("Көкжиек:", "Горизонт:")
      .replaceAll("кезең:", "период:")
      .replace(/(?<!\p{L})күн(?!\p{L})/gu, "дней")
    : visibleCore;
  const source = ru[normalizedCore] ?? normalizedCore;
  let localized = language === "kk" ? kk[source] ?? source : source;
  if (language === "kk") {
    localized = localized
      .replaceAll("Медицинская организация", "Медициналық ұйым")
      .replaceAll("Область прогноза:", "Болжам ауқымы:")
      .replaceAll("Горизонт:", "Көкжиек:")
      .replaceAll("период:", "кезең:")
      .replace(/(?<!\p{L})дней(?!\p{L})/gu, "күн");
  }
  return `${leading}${localized}${trailing}`;
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, updateLanguage] = useState<Language>("ru");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "kk") queueMicrotask(() => updateLanguage("kk"));
  }, []);

  const setLanguage = useCallback((next: Language) => {
    updateLanguage(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language === "kk" ? "kk" : "ru";
    document.documentElement.dataset.language = language;
    const localizeNode = (root: Node) => {
      const textNodes: Text[] = [];
      if (root.nodeType === Node.TEXT_NODE) textNodes.push(root as Text);
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      while (walker.nextNode()) textNodes.push(walker.currentNode as Text);
      textNodes.forEach((node) => {
        if (node.parentElement?.closest("script,style")) return;
        const current = node.nodeValue ?? "";
        const previous = originalText.get(node);
        const source = previous && current === previous.rendered ? previous.source : current;
        const next = translate(source, language);
        originalText.set(node, { source, rendered: next });
        if (current !== next) node.nodeValue = next;
      });

      const elements = root.nodeType === Node.ELEMENT_NODE ? [root as Element, ...(root as Element).querySelectorAll("*")] : [];
      elements.forEach((element) => {
        for (const name of ["aria-label", "title", "placeholder"]) {
          const current = element.getAttribute(name);
          if (current === null) continue;
          let values = originalAttributes.get(element);
          if (!values) { values = new Map(); originalAttributes.set(element, values); }
          const previous = values.get(name);
          const source = previous && current === previous.rendered ? previous.source : current;
          const next = translate(source, language);
          values.set(name, { source, rendered: next });
          if (next !== current) element.setAttribute(name, next);
        }
      });
    };

    localizeNode(document.body);
    const observer = new MutationObserver((mutations) => {
      mutations.forEach((mutation) => {
        if (mutation.type === "characterData") localizeNode(mutation.target);
        else if (mutation.type === "attributes") localizeNode(mutation.target);
        else mutation.addedNodes.forEach(localizeNode);
      });
    });
    observer.observe(document.body, { childList: true, characterData: true, attributes: true, attributeFilter: ["aria-label", "title", "placeholder"], subtree: true });
    return () => observer.disconnect();
  }, [language]);

  const value = useMemo<I18nValue>(() => ({ language, setLanguage, t: (text) => translate(text, language) }), [language, setLanguage]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}

export function LanguageSwitch({ compact = false }: { compact?: boolean }) {
  const { language, setLanguage } = useI18n();
  return (
    <div className="inline-flex shrink-0 rounded-lg border border-slate-200 bg-slate-50 p-0.5" role="group" aria-label="Язык интерфейса">
      {(["ru", "kk"] as const).map((item) => (
        <button
          key={item}
          type="button"
          aria-pressed={language === item}
          onClick={() => setLanguage(item)}
          className={`rounded-md px-2 py-1 text-[10px] font-extrabold transition ${language === item ? "bg-white text-cyan-900 shadow-sm" : "text-slate-500 hover:text-slate-800"}`}
        >
          {compact ? (item === "ru" ? "РУС" : "ҚАЗ") : (item === "ru" ? "Рус" : "Қаз")}
        </button>
      ))}
    </div>
  );
}
